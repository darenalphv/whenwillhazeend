#!/usr/bin/env python3
"""Build ``public/`` -- the tree Workers Static Assets serves.

    python3 scripts/build_static.py            # build
    python3 scripts/build_static.py --check    # build, exit 1 on any unhashed /static ref

Output::

    public/index.html              <- app/templates/index.html
    public/simulator/index.html    <- app/templates/simulator.html   (served at /simulator)
    public/static/**               <- app/static/**  (JS/CSS rewritten, see below)
    public/404.html                minimal not-found page
    public/_headers                cache + security headers for static responses

Cache busting
-------------
Every reference to a local static file gets ``?v=<first 10 hex of sha256>``:

* in HTML: any quoted ``/static/...`` URL (``src``/``href`` attributes, inline
  ``<script type="module">`` imports, preload links);
* in JS: static ``import``/``export ... from`` specifiers, literal dynamic
  ``import('...')``, ``new URL('...', import.meta.url)``, and any other string
  literal that is an absolute ``/static/...`` path to a file that exists;
* in CSS: ``url(...)`` and ``@import``.

**ES modules are hashed as a Merkle tree.** A module's version is the hash of
its *rewritten* bytes, and its rewritten bytes already contain its
dependencies' versions. So editing ``util.js`` changes util's hash, which
changes the import line in every module that imports it, which changes their
hashes, all the way up to the ``<script type="module">`` tag in the HTML. Every
URL the browser ever fetches under ``/static/`` therefore carries a hash that
changes whenever anything it (transitively) loads changes -- which is what lets
``_headers`` mark ``/static/*`` as ``immutable`` for a year. Import cycles are
handled by giving every module in a strongly-connected component a version
derived from the whole component.

A query string (rather than a hashed filename) is used because Workers Static
Assets match on pathname only, so ``/static/js/app.js?v=anything`` always
serves the current file: an old HTML page still in someone's browser cannot
404 its scripts after a deploy.

What cannot be hashed: specifiers built at runtime (template literals,
concatenation). They are reported as warnings (``--check`` makes them fatal),
because under the ``immutable`` header such a file could stay stale in a
browser for up to a year. Write literal specifiers.

Stdlib only.
"""

from __future__ import annotations

import argparse
import hashlib
import posixpath
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app"
STATIC_SRC = APP / "static"
TEMPLATES = APP / "templates"
OUT = ROOT / "public"

PAGES = {
    "index.html": "index.html",
    "simulator.html": "simulator/index.html",
}

HASH_LEN = 10
TEXT_REWRITE = {".js", ".mjs", ".css"}

# Origins the pages are allowed to use (CONTRACT_V2 + amendments). Used for the
# Content-Security-Policy, which ships in Report-Only mode: it logs violations
# in the browser console without blocking anything. Promote it to an enforcing
# Content-Security-Policy only after both pages have been checked clean.
CDN = "https://cdn.jsdelivr.net https://unpkg.com https://cdnjs.cloudflare.com"
TILES = ("https://tiles.openfreemap.org https://s3.amazonaws.com "
         "https://services.arcgisonline.com https://server.arcgisonline.com")
WEATHER = "https://api.open-meteo.com https://archive-api.open-meteo.com"
CSP = "; ".join([
    "default-src 'self'",
    f"script-src 'self' 'unsafe-inline' 'wasm-unsafe-eval' {CDN}",
    f"style-src 'self' 'unsafe-inline' https://fonts.googleapis.com {CDN}",
    f"font-src 'self' data: https://fonts.gstatic.com {CDN} https://tiles.openfreemap.org",
    f"img-src 'self' data: blob: {TILES} {CDN}",
    f"connect-src 'self' {TILES} {WEATHER} {CDN}",
    "worker-src 'self' blob:",
    "child-src 'self' blob:",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
])

HEADERS_FILE = f"""\
# Generated by scripts/build_static.py -- do not edit public/ by hand.
# Applies to Static Assets only; /api/* responses get their headers from worker/src/entry.py.

# Every /static URL the pages reference carries ?v=<content hash>, so the bytes
# behind a given URL never change: cache for a year, never revalidate.
/static/*
  Cache-Control: public, max-age=31536000, immutable

# HTML keeps the Workers default (public, max-age=0, must-revalidate + ETag), so
# a deploy is visible on the next page load and pulls the new hashed URLs.
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()
  Content-Security-Policy-Report-Only: {CSP}
"""

NOT_FOUND = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Not found — whenwillhazeend</title></head>
<body style="font:16px/1.6 system-ui,sans-serif;max-width:40rem;margin:4rem auto;padding:0 1rem">
<h1>Page not found</h1>
<p>There is nothing at this address. Go to the <a href="/">forecast</a> or the
<a href="/simulator">3D simulator</a>.</p>
</body></html>
"""

# --------------------------------------------------------------------------- #
# Reference scanners. Each yields (start, end, specifier) for the span holding
# the bare specifier (inside its quotes), so we can splice in "?v=".
# --------------------------------------------------------------------------- #

_Q = r"""(['"])([^'"\n]+?)\1"""
JS_PATTERNS = [
    # import x from '...'; import {a} from "..."; export * from '...'
    re.compile(r"""\b(?:import|export)\b[^'";]*?\bfrom\s*""" + _Q),
    # import '...';  (side-effect import)
    re.compile(r"""\bimport\s*""" + _Q),
    # import('...')
    re.compile(r"""\bimport\s*\(\s*""" + _Q + r"""\s*\)"""),
    # new URL('...', import.meta.url)
    re.compile(r"""\bnew\s+URL\s*\(\s*""" + _Q + r"""\s*,\s*import\.meta\.url"""),
    # any absolute '/static/...' string literal
    re.compile(r"""(['"`])(/static/[^'"`\s?#]+)\1"""),
]
JS_DYNAMIC = re.compile(r"""\bimport\s*\(\s*(?!['"])([^)]*)\)""")
CSS_PATTERNS = [
    re.compile(r"""url\(\s*(['"]?)([^'")\s]+)\1\s*\)"""),
    re.compile(r"""@import\s+""" + _Q),
]
# url("data:...") bodies can contain url(#id) of their own (inline SVG filters).
CSS_DATA_URI = re.compile(r"""url\(\s*(?:"data:[^"]*"|'data:[^']*'|data:[^)]*)\s*\)""")
HTML_PATTERN = re.compile(r"""(['"])(/static/[^'"\s?#]+)\1""")


def _spans(text: str, patterns, masks=()) -> list[tuple[int, int, str]]:
    seen: dict[int, tuple[int, int, str]] = {}
    masked = [(m.start(), m.end()) for mp in masks for m in mp.finditer(text)]
    for pat in patterns:
        for m in pat.finditer(text):
            if any(a <= m.start() < b for a, b in masked):
                continue
            spec = m.group(2)
            start = m.start(2)
            seen.setdefault(start, (start, m.end(2), spec))
    return sorted(seen.values())


def _resolve(spec: str, from_url: str, css: bool = False) -> str | None:
    """Map a specifier to a ``/static/...`` URL path, or None if it is external."""
    if spec.startswith(("data:", "http:", "https:", "//", "#", "blob:", "mailto:")):
        return None
    spec = spec.split("?", 1)[0].split("#", 1)[0]
    if spec.startswith("/"):
        url = posixpath.normpath(spec)
    elif spec.startswith(("./", "../")) or (css and ":" not in spec):
        # CSS url(foo.png) is relative; a bare JS specifier is not (import map/CDN).
        url = posixpath.normpath(posixpath.join(posixpath.dirname(from_url), spec))
    else:
        return None  # bare specifier (import map / CDN) -- not ours
    return url if url.startswith("/static/") else None


def _file_for(url: str) -> Path:
    return STATIC_SRC / url[len("/static/"):]


# --------------------------------------------------------------------------- #


class Builder:
    def __init__(self) -> None:
        self.warnings: list[str] = []
        self.version: dict[str, str] = {}      # /static/url -> hash
        self.rewritten: dict[str, bytes] = {}  # /static/url -> output bytes
        self.deps: dict[str, list[tuple[int, int, str, str]]] = {}
        self.texts: dict[str, str] = {}

    # -- graph ------------------------------------------------------------- #
    def scan(self) -> None:
        for path in sorted(STATIC_SRC.rglob("*")):
            if not path.is_file() or "__pycache__" in path.parts:
                continue
            url = "/static/" + path.relative_to(STATIC_SRC).as_posix()
            if path.suffix not in TEXT_REWRITE:
                self.version[url] = hashlib.sha256(path.read_bytes()).hexdigest()[:HASH_LEN]
                self.rewritten[url] = path.read_bytes()
                continue
            text = path.read_text(encoding="utf-8")
            self.texts[url] = text
            is_css = path.suffix == ".css"
            pats = CSS_PATTERNS if is_css else JS_PATTERNS
            refs = []
            for start, end, spec in _spans(text, pats, (CSS_DATA_URI,) if is_css else ()):
                target = _resolve(spec, url, css=is_css)
                if target is None:
                    continue
                if not _file_for(target).is_file():
                    self.warnings.append(f"{url}: reference to missing file {spec!r}")
                    continue
                refs.append((start, end, spec, target))
            self.deps[url] = refs
            if path.suffix != ".css":
                for m in JS_DYNAMIC.finditer(text):
                    line = text.count("\n", 0, m.start()) + 1
                    self.warnings.append(
                        f"{url}:{line}: dynamic import with a computed specifier "
                        f"({m.group(1).strip()[:60]!r}) cannot be content-hashed")

    def _sccs(self) -> list[list[str]]:
        """Tarjan; returns SCCs in reverse topological order (deps first)."""
        index: dict[str, int] = {}
        low: dict[str, int] = {}
        stack: list[str] = []
        on: set[str] = set()
        out: list[list[str]] = []
        counter = [0]
        sys.setrecursionlimit(10000)

        def visit(v: str) -> None:
            index[v] = low[v] = counter[0]
            counter[0] += 1
            stack.append(v)
            on.add(v)
            for *_, w in self.deps.get(v, []):
                if w not in self.deps:
                    continue  # binary/leaf, already versioned
                if w not in index:
                    visit(w)
                    low[v] = min(low[v], low[w])
                elif w in on:
                    low[v] = min(low[v], index[w])
            if low[v] == index[v]:
                comp = []
                while True:
                    w = stack.pop()
                    on.discard(w)
                    comp.append(w)
                    if w == v:
                        break
                out.append(sorted(comp))

        for v in sorted(self.deps):
            if v not in index:
                visit(v)
        return out

    def _render(self, url: str, versions: dict[str, str]) -> str:
        text = self.texts[url]
        parts, pos = [], 0
        for start, end, spec, target in self.deps[url]:
            base = spec.split("?", 1)[0].split("#", 1)[0]
            parts.append(text[pos:start])
            parts.append(f"{base}?v={versions[target]}")
            pos = end
        parts.append(text[pos:])
        return "".join(parts)

    def hash_all(self) -> None:
        for comp in self._sccs():
            members = set(comp)
            if len(comp) == 1 and not any(t == comp[0] for *_, t in self.deps[comp[0]]):
                url = comp[0]
                out = self._render(url, self.version)
                self.version[url] = hashlib.sha256(out.encode()).hexdigest()[:HASH_LEN]
                self.rewritten[url] = out.encode()
                continue
            # Cycle: one version for the whole component, from its members'
            # source plus the versions of everything outside it they import.
            h = hashlib.sha256()
            for url in comp:
                h.update(url.encode() + b"\0" + self.texts[url].encode())
                for *_, t in self.deps[url]:
                    if t not in members:
                        h.update(f"{t}={self.version[t]}".encode())
            v = h.hexdigest()[:HASH_LEN]
            for url in comp:
                self.version[url] = v
            for url in comp:
                self.rewritten[url] = self._render(url, self.version).encode()

    # -- pages ------------------------------------------------------------- #
    def page(self, src: Path) -> str:
        html = src.read_text(encoding="utf-8")
        if "{{" in html or "{%" in html:
            self.warnings.append(f"{src.name}: contains Jinja syntax; it is served verbatim")

        def sub(m: re.Match) -> str:
            q, spec = m.group(1), m.group(2)
            if spec not in self.version:
                self.warnings.append(f"{src.name}: reference to missing file {spec!r}")
                return m.group(0)
            return f"{q}{spec}?v={self.version[spec]}{q}"

        return HTML_PATTERN.sub(sub, html)

    # -- output ------------------------------------------------------------ #
    def write(self) -> dict[str, int]:
        if OUT.exists():
            shutil.rmtree(OUT)
        (OUT / "static").mkdir(parents=True)
        for url, data in self.rewritten.items():
            dest = OUT / url.lstrip("/")
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(data)
        for name, rel in PAGES.items():
            src = TEMPLATES / name
            if not src.is_file():
                self.warnings.append(f"template {src} missing; {rel} not built")
                continue
            dest = OUT / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(self.page(src), encoding="utf-8")
        (OUT / "404.html").write_text(NOT_FOUND, encoding="utf-8")
        (OUT / "_headers").write_text(HEADERS_FILE, encoding="utf-8")
        # Same policy as machine-readable JSON, for app.main when it serves
        # public/ itself (the DigitalOcean container) rather than a CDN.
        (OUT / "_headers.json").write_text(json.dumps({
            "static_cache_control": "public, max-age=31536000, immutable",
            "html_headers": {
                "X-Content-Type-Options": "nosniff",
                "Referrer-Policy": "strict-origin-when-cross-origin",
                "Permissions-Policy": "camera=(), microphone=(), geolocation=(), payment=()",
                "Content-Security-Policy-Report-Only": CSP,
            },
        }, indent=2), encoding="utf-8")
        files = [p for p in OUT.rglob("*") if p.is_file()]
        return {"files": len(files), "bytes": sum(p.stat().st_size for p in files)}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if any static reference could not be hashed")
    args = ap.parse_args()

    if not STATIC_SRC.is_dir():
        print(f"build_static: {STATIC_SRC} not found", file=sys.stderr)
        return 1
    b = Builder()
    b.scan()
    b.hash_all()
    stats = b.write()
    for w in b.warnings:
        print(f"build_static: WARNING {w}", file=sys.stderr)
    print(f"build_static: {stats['files']} files, {stats['bytes'] / 1024:.0f} KiB -> public/ "
          f"({len(b.version)} static assets hashed)")
    return 1 if (args.check and b.warnings) else 0


if __name__ == "__main__":
    raise SystemExit(main())
