"""Cloudflare Python Worker entry for whenwillhazeend.com.

Routing (wrangler.jsonc): Workers Static Assets serve everything except
``/api/*``, which runs this Worker. Here we:

1. hand the request to the unchanged FastAPI app (``app.main:app``) through the
   Workers ASGI adapter;
2. put deterministic responses in the edge cache (Cache API), so a repeated
   seeded simulation costs one cache lookup instead of hundreds of ms of CPU;
3. on the daily Cron Trigger, record the model's forecast odds "as of today"
   in Workers KV, and merge those recorded points into
   ``GET /api/forecast/history``.

Nothing here computes a number. The model layer computes; this file only
caches, records and routes.

Python Workers snapshot the Wasm heap after this module's top-level code runs
at deploy time, so whatever is imported/loaded here is free on a cold start.
"""

from __future__ import annotations

import hashlib
import json
import logging
from datetime import datetime, timezone
from urllib.parse import urlsplit

import asgi
from workers import WorkerEntrypoint

from app.main import app
from build_info import APP_HASH

log = logging.getLogger("whenwillhazeend.worker")

# --------------------------------------------------------------------------- #
# Snapshot warm-up. app.api.deps imports the model lazily (so a broken model
# file cannot take the API down); here we import it eagerly *but guarded*, so
# that numpy, the model modules and the small datasets land in the deploy-time
# memory snapshot. A failure is swallowed: the request path will then import
# lazily and report the failing component as a 503, exactly as it does today.
# --------------------------------------------------------------------------- #

WARM_MODULES = ("numpy", "app.data.loader", "app.model.meteo", "app.model.kbdi",
                "app.model.burn", "app.model.stock", "app.model.dispersion",
                "app.model.haze3d", "app.model.history")
WARM_LOADERS = ("load_seasons", "load_fuel_stock", "load_regions", "load_receptors",
                "load_climatology", "load_enso", "load_provenance")


def _warm() -> list[str]:
    failed = []
    for mod in WARM_MODULES:
        try:
            __import__(mod)
        except Exception:  # noqa: BLE001
            failed.append(mod)
    try:
        from app.data import loader

        for fn in WARM_LOADERS:
            getattr(loader, fn)()
    except Exception:  # noqa: BLE001
        failed.append("app.data.loader:preload")
    return failed


WARM_FAILED = _warm()

# --------------------------------------------------------------------------- #
# Edge cache policy
#
# Responses generated by a Worker are NOT cached by Cloudflare's CDN on their
# own -- Cache-Control on them only reaches browsers. Edge caching therefore
# goes through the Cache API (caches.default), which is per data centre and
# only active on a custom domain (a no-op on *.workers.dev).
# The key includes APP_HASH (digest of the staged app code + data), so a deploy
# that changes the model or its data never serves a pre-deploy result.
# --------------------------------------------------------------------------- #

HOUR = 3600
DAY = 86400

GET_TTL_EXACT = {
    "/api/history": DAY,
    "/api/regions": DAY,
    "/api/fuel": DAY,
    "/api/receptors": DAY,
    "/api/provenance": DAY,
    "/api/forecast/odds": HOUR,       # recomputed against live weather
    "/api/forecast/history": HOUR,    # grows once a day (cron)
    "/api/meteo": 15 * 60,            # live Open-Meteo, or climatology fallback
}
GET_TTL_PREFIX = {
    "/api/history/": DAY,             # /api/history/{year}, /api/history/compare
}
# POST path -> (edge TTL, needs a seed to be deterministic, varies by UTC day)
POST_POLICY = {
    "/api/simulate/season": (HOUR, True, True),      # as_of defaults to today; live weather
    "/api/simulate/exhaustion": (DAY, True, False),
    "/api/dispersion": (DAY, False, False),          # no RNG
    "/api/simulate/haze3d": (DAY, False, False),     # no RNG, no live weather
}
# Responses that fell back to climatology because Open-Meteo was unreachable are
# cached only briefly, so a blip upstream does not pin a no-live-weather answer
# for an hour. path -> the boolean field that says the answer used live weather.
LIVE_FLAG = {
    "/api/meteo": "live",
    "/api/simulate/season": "live_weather",
}
FALLBACK_TTL = 120
BROWSER_MAX_AGE = 300
CACHE_HOST = "https://edge-cache.whenwillhazeend.invalid"


def _utc_today() -> str:
    return datetime.now(timezone.utc).date().isoformat()


def cache_plan(method: str, path: str, query: str, body: bytes | None):
    """Return ``(cache key URL, ttl seconds)``, or None if the request must not be cached."""
    if method == "GET":
        ttl = GET_TTL_EXACT.get(path)
        if ttl is None:
            ttl = next((t for p, t in GET_TTL_PREFIX.items() if path.startswith(p)), None)
        if ttl is None:
            return None
        return f"{CACHE_HOST}/{APP_HASH}{path}?{query}", ttl
    if method == "POST" and path in POST_POLICY:
        ttl, needs_seed, daily = POST_POLICY[path]
        try:
            payload = json.loads(body or b"{}")
        except ValueError:
            return None
        if not isinstance(payload, dict):
            return None
        if needs_seed and payload.get("seed") is None:
            return None  # an unseeded run asks for a fresh draw; never cache it
        canon = json.dumps(payload, sort_keys=True, separators=(",", ":"))
        digest = hashlib.sha256(canon.encode()).hexdigest()[:32]
        day = _utc_today() if daily else "-"
        return f"{CACHE_HOST}/{APP_HASH}{path}?d={day}&b={digest}", ttl
    return None


def _with_headers(js_response, headers: dict[str, str]):
    """Copy a JS Response (making its headers mutable) and set ``headers``."""
    from js import Response as JSResponse

    out = JSResponse.new(js_response.body, js_response)
    for k, v in headers.items():
        out.headers.set(k, v)
    return out


async def app_fetch(request, env, ctx):
    return await asgi.fetch(app, request, env, ctx)


async def cached(handler, request, env, ctx):
    """Serve ``handler``'s response through the edge cache when the policy allows."""
    from js import Request as JSRequest
    from js import caches

    parts = urlsplit(request.url)
    method = request.method
    body = await request.clone().bytes() if method == "POST" else None
    plan = cache_plan(method, parts.path, parts.query, body)
    if plan is None:
        resp = await handler(request, env, ctx)
        return _with_headers(resp, {"Cache-Control": "no-store"})

    key_url, ttl = plan
    key = JSRequest.new(key_url)
    browser = f"public, max-age={BROWSER_MAX_AGE}" if method == "GET" else "no-store"
    try:
        hit = await caches.default.match(key)
    except Exception:  # noqa: BLE001 - a cache failure must never fail the request
        hit = None
    if hit is not None:
        return _with_headers(hit, {"Cache-Control": browser, "X-WWHE-Cache": "HIT"})

    resp = await handler(request, env, ctx)
    ctype = resp.headers.get("content-type") or ""
    if resp.status != 200 or not ctype.startswith("application/json"):
        return _with_headers(resp, {"Cache-Control": "no-store"})
    flag = LIVE_FLAG.get(parts.path)
    if flag:
        try:
            if json.loads(await resp.clone().text()).get(flag) is False:
                ttl = min(ttl, FALLBACK_TTL)
        except Exception:  # noqa: BLE001
            ttl = min(ttl, FALLBACK_TTL)
    stored = _with_headers(resp.clone(), {"Cache-Control": f"public, max-age={ttl}"})
    try:
        ctx.waitUntil(caches.default.put(key, stored))
    except Exception:  # noqa: BLE001
        log.warning("edge cache put failed for %s", key_url, exc_info=True)
    return _with_headers(resp, {"Cache-Control": browser, "X-WWHE-Cache": "MISS"})


# --------------------------------------------------------------------------- #
# Forecast-odds history: recorded daily by cron into KV, merged on read.
#
# KV binding FORECAST_KV is optional: without it, /api/forecast/history is the
# app's own response untouched and the cron is a logged no-op. Keys:
#   odds/<YYYY-MM-DD>   the full /api/forecast/odds response computed that day
#   history/v1          {"series": [point, ...]} sorted by as_of
# A point has the /api/forecast/history series shape plus "recorded": "live":
# the model really published these odds that day, so it cannot contain hindsight.
# --------------------------------------------------------------------------- #

KV_BINDING = "FORECAST_KV"
HISTORY_KEY = "history/v1"


def _kv(env):
    try:
        return getattr(env, KV_BINDING)
    except Exception:  # noqa: BLE001
        return None


def p50_from_distribution(odds: dict) -> str | None:
    acc = 0.0
    for o in ((odds.get("distribution") or {}).get("outcomes")) or []:
        acc += float(o.get("p") or 0.0)
        if acc >= 0.5:
            return o.get("end") or o.get("start")
    return None


def point_from_odds(odds: dict, as_of: str) -> dict:
    return {
        "as_of": odds.get("as_of") or as_of,
        "p50_end_date": odds.get("p50_end_date") or p50_from_distribution(odds),
        "markets": {m["id"]: m.get("yes") for m in odds.get("markets") or [] if "id" in m},
        "n_sims": odds.get("n_sims"),
        "season_active": odds.get("season_active"),
        "recorded": "live",
        "recorded_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }


async def _kv_get_json(kv, key: str):
    raw = await kv.get(key)
    if raw is None:
        return None
    try:
        return json.loads(str(raw))
    except ValueError:
        return None


async def record_daily_odds(env, scheduled_ms: float | None = None) -> dict:
    """Compute today's odds through the app itself and append them to KV."""
    from js import Request as JSRequest

    kv = _kv(env)
    if kv is None:
        return {"ok": False, "reason": f"no {KV_BINDING} binding"}
    when = (datetime.fromtimestamp(scheduled_ms / 1000, timezone.utc)
            if scheduled_ms else datetime.now(timezone.utc))
    as_of = when.date().isoformat()
    req = JSRequest.new(f"https://internal.invalid/api/forecast/odds?as_of={as_of}")
    resp = await asgi.fetch(app, req, env)
    text = await resp.text()
    if resp.status != 200:
        return {"ok": False, "reason": f"/api/forecast/odds -> {resp.status}", "body": text[:300]}
    point = point_from_odds(json.loads(text), as_of)

    await kv.put(f"odds/{point['as_of']}", text)
    hist = await _kv_get_json(kv, HISTORY_KEY) or {"series": []}
    series = [p for p in hist.get("series", []) if p.get("as_of") != point["as_of"]]
    series.append(point)
    series.sort(key=lambda p: p.get("as_of") or "")
    await kv.put(HISTORY_KEY, json.dumps({"series": series}, separators=(",", ":")))
    return {"ok": True, "as_of": point["as_of"], "points": len(series)}


async def forecast_history(request, env, ctx):
    """The app's history (build-time hindcast) with KV-recorded live points merged in."""
    from js import Response as JSResponse

    resp = await app_fetch(request, env, ctx)
    kv = _kv(env)
    if kv is None:
        return resp
    try:
        recorded = (await _kv_get_json(kv, HISTORY_KEY) or {}).get("series") or []
    except Exception:  # noqa: BLE001
        log.warning("KV read failed; serving history without recorded points", exc_info=True)
        return resp
    if not recorded:
        return resp

    base = None
    if resp.status == 200:
        try:
            base = json.loads(await resp.text())
        except ValueError:
            base = None
    if not isinstance(base, dict):
        base = {
            "series": [],
            "method": ("Each point is the model's odds exactly as published on that "
                       "day, recorded once daily by a scheduled job."),
            "caveats": [],
        }
    by_day = {p.get("as_of"): p for p in base.get("series") or []}
    for p in recorded:  # a live recording beats a reconstruction of the same day
        by_day[p.get("as_of")] = p
    base["series"] = [by_day[k] for k in sorted(k for k in by_day if k)]
    base["recorded_points"] = len(recorded)
    base.setdefault("computed_at", recorded[-1].get("recorded_at"))
    from js import Object
    from pyodide.ffi import to_js

    init = to_js({"status": 200, "headers": {"content-type": "application/json"}},
                 dict_converter=Object.fromEntries)
    return JSResponse.new(json.dumps(base, separators=(",", ":")), init)


# --------------------------------------------------------------------------- #


class Default(WorkerEntrypoint):
    async def fetch(self, request):
        path = urlsplit(request.url).path
        if path == "/api/forecast/history" and request.method == "GET":
            return await cached(forecast_history, request, self.env, self.ctx)
        return await cached(app_fetch, request, self.env, self.ctx)

    async def scheduled(self, controller, env, ctx):
        result = await record_daily_odds(self.env, getattr(controller, "scheduledTime", None))
        print(f"forecast-odds cron: {json.dumps(result)}")
