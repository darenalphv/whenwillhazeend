#!/usr/bin/env python3
"""Stage the Python Worker's module tree into worker/src/.

Wrangler uploads every ``*.py`` (and, via the rule in wrangler.jsonc, every
``*.json``) under the directory that holds ``main`` -- ``worker/src/``. The app
lives in ``app/`` at the repo root, so this copies only what the API needs to
run into ``worker/src/app/``:

* ``app/**/*.py``  -- except ``app/model/calibrate.py`` (build-time fit; needs scipy,
  which is deliberately not shipped to the Worker);
* ``app/**/*.json`` -- the bundled datasets (``app/data/**``) and model
  parameters (``app/model/*.json``), read with ``open()`` at request time.

``app/static/`` and ``app/templates/`` are NOT staged: Workers Static Assets serve
them from ``public/`` (see ``scripts/build_static.py``).

It also writes ``worker/src/build_info.py`` (``APP_HASH``: a digest of everything
staged), used by entry.py to version the edge cache.

``worker/src/app/`` and ``build_info.py`` are generated -- never edit it, it is re-synced on every run.
Stdlib only, so it runs under any Python >= 3.9.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_APP = ROOT / "app"
DEST = ROOT / "worker" / "src" / "app"
BUILD_INFO = ROOT / "worker" / "src" / "build_info.py"

SKIP_DIRS = {"static", "templates", "__pycache__"}
SKIP_FILES = {Path("model/calibrate.py")}
KEEP_SUFFIXES = {".py", ".json"}


def _write_if_changed(dest: Path, data: bytes) -> None:
    # Sync rather than wipe-and-copy: `wrangler dev` watches this tree, and a
    # half-deleted package mid-reload crashes the local runtime.
    if dest.is_file() and dest.read_bytes() == data:
        return
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(data)


def stage() -> tuple[int, int]:
    n_files = n_bytes = 0
    wanted: set[Path] = set()
    digest = hashlib.sha256()
    for path in sorted(SRC_APP.rglob("*")):
        rel = path.relative_to(SRC_APP)
        if any(part in SKIP_DIRS for part in rel.parts):
            continue
        if not path.is_file() or path.suffix not in KEEP_SUFFIXES:
            continue
        if rel in SKIP_FILES:
            continue
        data = path.read_bytes()
        _write_if_changed(DEST / rel, data)
        wanted.add(DEST / rel)
        digest.update(rel.as_posix().encode() + b"\0" + data)
        n_files += 1
        n_bytes += path.stat().st_size
    # The edge-cache key in entry.py includes this, so a deploy that changes the
    # model or its data can never be answered from a cached pre-deploy result.
    _write_if_changed(BUILD_INFO, (
        '"""Generated by worker/stage_app.py -- do not edit."""\n'
        f'APP_HASH = "{digest.hexdigest()[:16]}"\n').encode())
    # Remove files that no longer exist in app/ (and dirs left empty).
    for stale in sorted(DEST.rglob("*"), reverse=True):
        if stale.is_file() and stale not in wanted:
            stale.unlink()
        elif stale.is_dir() and not any(stale.iterdir()):
            stale.rmdir()
    return n_files, n_bytes


def main() -> int:
    if not (SRC_APP / "main.py").is_file():
        print(f"stage_app: {SRC_APP / 'main.py'} not found", file=sys.stderr)
        return 1
    n, b = stage()
    print(f"stage_app: {n} files, {b / 1024:.0f} KiB -> {DEST.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
